"""Extract the opening sample from its verified PyTorch-generated MIDI.

Install music21, then run `python scripts/export_showcase.py` from the project.
Use `--check` to verify the checked-in browser module without modifying it.
"""
import argparse
import hashlib
from pathlib import Path

from music21 import midi

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "model-demo" / "lstm-demo-16-bars.mid"
OUTPUT = ROOT / "web" / "showcase.js"
MIDI_SHA256 = "bccb5de7762b6e6bcf8b06bf3e04b2e150e970011b28b07db8e80036c1bc6c63"


def read_notes():
    data = SOURCE.read_bytes()
    if hashlib.sha256(data).hexdigest() != MIDI_SHA256:
        raise ValueError("The opening sample must match its verified MIDI source.")
    score = midi.MidiFile()
    score.readstr(data)
    if (score.format, len(score.tracks), score.ticksPerQuarterNote) != (0, 1, 480):
        raise ValueError("Unexpected sample track format or resolution.")

    tick = 0
    notes, pending = [], {}
    for event in score.tracks[0].events:
        if isinstance(event, midi.DeltaTime):
            tick += event.time
        elif event.isNoteOn():
            pending[(event.channel, event.pitch)] = (tick, event.velocity)
        elif event.isNoteOff():
            start, velocity = pending.pop((event.channel, event.pitch))
            notes.append((event.pitch, start, tick - start, velocity))
        elif event.type == midi.MetaEvents.SET_TEMPO:
            if tick or int.from_bytes(event.data, "big") != 625000:
                raise ValueError("Expected a fixed tempo of 96 BPM.")
        elif event.type == midi.ChannelVoiceMessages.PROGRAM_CHANGE:
            if tick or event.parameter1 != 0:
                raise ValueError("Expected the acoustic piano program.")
    if pending or len(notes) != 109 or tick != 16 * 4 * 480:
        raise ValueError("Expected 109 complete notes over exactly 16 bars.")
    return sorted(notes, key=lambda note: note[1])


def render():
    rows = "\n".join(f"  [{pitch}, {start}, {duration}, {velocity}]," for pitch, start, duration, velocity in read_notes())
    return f'''// Generated by scripts/export_showcase.py from the verified LSTM demo MIDI.
// Source SHA-256: {MIDI_SHA256}
import {{ trackSchema }} from "./music.js";

export const SHOWCASE_ID = "built-in-lstm-demo-16-bars";

// [MIDI pitch, start tick, duration ticks, note-on velocity] at 480 PPQ.
const events = [
{rows}
];

// Epoch 6 synthetic LSTM, conditioned on Am, F, C, G at temperature 0.85.
// This built-in study has no recording timestamp or user-library owner.
export function createShowcaseTrack() {{
  const ticksPerSecond = (96 / 60) * 480;
  return trackSchema.parse({{
    id: SHOWCASE_ID,
    title: "Somewhere, softly",
    created_at: "",
    bars: 16,
    tempo: 96,
    temperature: 0.85,
    instrument: "piano",
    duration: 40,
    model: "lstm-synthetic-demo",
    notes: events.map(([pitch, start, duration, velocity]) => ({{
      pitch,
      start: start / ticksPerSecond,
      duration: duration / ticksPerSecond,
      velocity,
    }})),
  }});
}}
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    source = render()
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != source:
            raise SystemExit("The opening sample differs from the source MIDI. Run this script to regenerate it.")
    else:
        OUTPUT.write_text(source, encoding="utf-8", newline="\n")
    print("Opening sample verified: 109 notes, 30,720 ticks, 16 bars at 96 BPM.")


if __name__ == "__main__":
    main()
